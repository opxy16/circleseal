// Copies compiled contract ABIs into the web app as TypeScript constants (run after `npx hardhat compile`).
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const outDir = path.join(root, "web", "src", "lib", "abi");
fs.mkdirSync(outDir, { recursive: true });

const contracts = [
  ["AjoPassbook", "contracts/AjoPassbook.sol"],
  ["AjoForwarder", "contracts/AjoForwarder.sol"],
  ["AjoCircle", "contracts/AjoCircle.sol"],
  ["MockStable", "contracts/test/MockStable.sol"],
];

for (const [name, source] of contracts) {
  const artifact = JSON.parse(fs.readFileSync(path.join(root, "artifacts", source, `${name}.json`), "utf8"));
  const ts = `// Generated by scripts/export-abi.cjs. Do not edit by hand.\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(outDir, `${name}.ts`), ts);
  console.log(`wrote web/src/lib/abi/${name}.ts`);
}
